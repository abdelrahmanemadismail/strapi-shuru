async function seedServicesPage(strapi) {
  try {
    const uid = 'api::services-page.services-page';
    console.log('Seeding Services Page Single Type...');

    // Check if services-page model exists
    if (!strapi.contentTypes[uid]) {
      console.log('Services page content type not registered in Strapi.');
      return;
    }

    // Process Arabic (default locale)
    const existing = await strapi.documents(uid).findFirst({
      locale: 'ar',
      populate: {
        blocks: { populate: '*' },
        trustMetrics: true,
        seo: true,
      }
    });

    if (existing) {
      console.log('Updating existing Arabic Services Page...');
      await strapi.documents(uid).update({
        documentId: existing.documentId,
        locale: 'ar',
        data: servicesPageData.ar,
        status: 'published',
      });
    } else {
      console.log('Creating new Arabic Services Page...');
      const created = await strapi.documents(uid).create({
        data: servicesPageData.ar,
        locale: 'ar',
        status: 'published',
      });

      // Create English version linked to documentId
      console.log('Creating English Services Page localization...');
      await strapi.documents(uid).create({
        documentId: created.documentId,
        data: servicesPageData.en,
        locale: 'en',
        status: 'published',
      });
    }

    // Ensure English localization exists
    const existingEn = await strapi.documents(uid).findFirst({
      locale: 'en',
      populate: {
        blocks: { populate: '*' },
        trustMetrics: true,
        seo: true,
      }
    });

    if (existingEn) {
      console.log('Updating existing English Services Page...');
      await strapi.documents(uid).update({
        documentId: existingEn.documentId,
        locale: 'en',
        data: servicesPageData.en,
        status: 'published',
      });
    }

    console.log('✅ Services Page Single Type seeded successfully!');
  } catch (error) {
    console.error('❌ Error seeding Services Page Single Type:', error);
  }
}

module.exports = { seedServicesPage, servicesPageData };

if (require.main === module) {
  const { createStrapi } = require('@strapi/strapi');
  createStrapi().load().then(async (strapiInstance) => {
    await seedServicesPage(strapiInstance);
    process.exit(0);
  }).catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
